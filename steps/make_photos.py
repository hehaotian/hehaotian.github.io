#!/usr/bin/env python3
"""Regenerate photos.js from the files in img/ (names like cityname_YYYYMM.jpg).
Run after adding or removing photos:  python3 make_photos.py"""
import json, os, re
root = os.path.dirname(os.path.abspath(__file__))
files = sorted(f for f in os.listdir(os.path.join(root, "img"))
               if re.match(r"^[A-Za-z]+_\d{6}(_\d+)?\.(jpe?g|png|gif|webp)$", f, re.I))
with open(os.path.join(root, "photos.js"), "w") as out:
    out.write("// generated by make_photos.py from img/ - do not edit by hand\nwindow.PHOTOS = " + json.dumps(files, indent=1) + ";\n")
print(len(files), "photos")
